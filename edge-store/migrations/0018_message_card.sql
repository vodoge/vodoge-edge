--    这跟号码那件事是同一个毛病的两面（0011 记下了「号码读自哪张卡」）：卡是会
--    换的，凡是属于卡的事实都得跟卡绑在一起，否则它会安静地跟到下一张卡名下。
--
-- ⚠️ 只对**这条迁移之后**收到的短信有效。已经在库里的行留 NULL —— 那是诚实的
--    「不知道」，不是「没有卡」。绝不能拿模组当前的卡去回填：那等于把一个猜测
--    写成事实，而且是个看起来很像真的猜测。
