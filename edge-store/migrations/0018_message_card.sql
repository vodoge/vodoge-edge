-- 🔴 在这之前，短信只挂 IMEI。而 IMEI 认的是那根棒，不是那张卡 —— 换一张卡，
--    同一根棒继续收，历史里两张卡的消息就混在一起，而且**分不回去**：当时是哪张
--    卡这件事从来没有被记下来过，事后没有任何依据可以重建。
